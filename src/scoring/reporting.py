"""Rendering helpers for model-comparison reports."""

from __future__ import annotations

from pathlib import Path
from typing import Any


def render_markdown_table(headers: list[str], rows: list[list[str]]) -> str:
    sep = "| " + " | ".join(headers) + " |"
    rule = "| " + " | ".join(["---"] * len(headers)) + " |"
    body = ["| " + " | ".join(row) + " |" for row in rows]
    return "\n".join([sep, rule, *body])


def latex_escape(text: str) -> str:
    mapping = {
        "\\": r"\\textbackslash{}",
        "&": r"\\&",
        "%": r"\\%",
        "$": r"\\$",
        "#": r"\\#",
        "_": r"\\_",
        "{": r"\\{",
        "}": r"\\}",
        "~": r"\\textasciitilde{}",
        "^": r"\\textasciicircum{}",
    }
    return "".join(mapping.get(ch, ch) for ch in text)


def qtype_compact_label(qtype: str) -> str:
    mapped = {
        "direct": "Dir",
        "hop": "Hop",
        "query_builder": "QB",
        "impossible": "Imp",
    }
    return mapped.get(qtype, qtype.replace("_", " ").title())


def latex_model_cell(model: str) -> str:
    # Allow wrapping at punctuation so long model IDs do not force oversized tables.
    pieces: list[str] = []
    for ch in model:
        pieces.append(latex_escape(ch))
        if ch in "-:._":
            pieces.append(r"\allowbreak{}")
    return "".join(pieces)


def dataset_compact_label(dataset: str) -> str:
    if dataset == "hypmol":
        return "HypMol"
    if dataset == "wiproflex":
        return "Wiproflex"
    return dataset.title()


def latex_prf_cell(prf: str) -> str:
    parts = [p.strip() for p in prf.split("/")]
    if len(parts) != 3:
        return latex_escape(prf)
    p, r, f1 = (latex_escape(parts[0]), latex_escape(parts[1]), latex_escape(parts[2]))
    return rf"\makecell[r]{{\textbf{{P}} {p}\\\textbf{{R}} {r}\\\textbf{{F1}} {f1}}}"


def latex_share_cell(share: str) -> str:
    value_part, sep, pct_part = share.partition(" (")
    if not sep:
        return latex_escape(share)
    value_render = latex_escape(value_part.replace("/", " / "))
    pct_render = latex_escape("(" + pct_part)
    return rf"\makecell[r]{{{value_render}\\{pct_render}}}"


def _parse_prf_f1_value(prf: str) -> float | None:
    clean = prf.strip()
    if not clean:
        return None
    if "/" not in clean:
        try:
            return float(clean)
        except ValueError:
            return None
    parts = [p.strip() for p in clean.split("/")]
    if len(parts) != 3:
        return None
    try:
        return float(parts[2])
    except ValueError:
        return None


def render_cross_dataset_prf_latex(
    dataset_order: list[str],
    rows: list[list[str]],
) -> str:
    n_metric_cols = 2 * len(dataset_order)
    colspec = "|l|l|" + "|".join(["c"] * n_metric_cols) + "|"

    group_header = [r"\thead{Size\\Class}", r"\thead{Model}"]
    sub_header = ["", ""]
    for dataset in dataset_order:
        label = latex_escape(dataset_compact_label(dataset))
        align = "c|"
        group_header.append(rf"\multicolumn{{2}}{{{align}}}{{\thead{{{label}}}}}")
        sub_header.append(r"\thead{Ans\\F1}")
        sub_header.append(r"\thead{All\\F1}")

    max_f1_by_col: list[float | None] = []
    for col_idx in range(n_metric_cols):
        vals = []
        for row in rows:
            raw = row[2 + col_idx].strip()
            f1 = _parse_prf_f1_value(raw) if raw else None
            if f1 is not None:
                vals.append(f1)
        max_f1_by_col.append(max(vals) if vals else None)

    body: list[str] = []
    prev_size_class: str | None = None
    for row in rows:
        size_class = row[0]
        model = row[1]
        values = row[2:]
        is_new_class = prev_size_class is None or size_class != prev_size_class
        prev_size_class = size_class

        # Show class label only on first row of each class block.
        size_class_cell = latex_escape(size_class) if is_new_class else ""

        rendered = [
            rf"\makecell[l]{{\footnotesize {size_class_cell}}}",
            rf"\makecell[l]{{\footnotesize {latex_model_cell(model)}}}",
        ]
        for col_idx, val in enumerate(values):
            clean = val.strip()
            if not clean:
                rendered.append("--")
                continue
            cell = latex_escape(clean)
            best = max_f1_by_col[col_idx]
            cell_f1 = _parse_prf_f1_value(clean)
            if best is not None and cell_f1 is not None and abs(cell_f1 - best) < 1e-12:
                cell = rf"\textbf{{{cell}}}"
            rendered.append(cell)
        body.append(" & ".join(rendered) + r" \\")

    return "\n".join(
        [
            "% Auto-generated by src.scoring.compare_models",
            r"\renewcommand\theadfont{\bfseries}",
            "",
            r"\begin{table}[htbp]",
            r"\centering",
            r"\caption{Cross-dataset F1 score by model size class}",
            r"\label{tab:cross_dataset_prf}",
            r"\small",
            r"\setlength{\tabcolsep}{4pt}",
            r"\renewcommand{\arraystretch}{1.0}",
            rf"\begin{{tabular}}{{{colspec}}}",
            r"\hline",
            " & ".join(group_header) + r" \\",
            r"\hline",
            " & ".join(sub_header) + r" \\",
            r"\hline",
            *body,
            r"\hline",
            r"\end{tabular}",
            r"\end{table}",
            "",
        ]
    )


